import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docxPath = join(
  root,
  "supabase/functions/submit-provider-application/assets/Agency-Subscriber-Agreement.docx",
);
const outPath = join(
  root,
  "supabase/functions/submit-provider-application/agreementAttachment.ts",
);

const base64 = readFileSync(docxPath).toString("base64");

writeFileSync(
  outPath,
  `// Generated by scripts/encode-agency-agreement.mjs. Do not edit by hand.
// Replace assets/Agency-Subscriber-Agreement.docx, then re-run this script.

export const AGREEMENT_FILENAME = "Agency-Subscriber-Agreement.docx";
export const AGREEMENT_CONTENT_TYPE =
  "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
export const AGREEMENT_BASE64 =
  "${base64}";
`,
);

console.log(`Wrote ${outPath} (${base64.length} chars)`);
